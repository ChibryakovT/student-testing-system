-- Расписание занятий (недельное, с числителем и знаменателем) и расписание сессии

CREATE TABLE lessons (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id      BIGINT      NOT NULL REFERENCES study_groups (id) ON DELETE CASCADE,
    day_of_week   INTEGER     NOT NULL,
    pair_no       INTEGER     NOT NULL,
    week_type     VARCHAR(20) DEFAULT 'EVERY' NOT NULL,
    subject_id    BIGINT      REFERENCES subjects (id) ON DELETE CASCADE,
    title         VARCHAR(150),
    teacher_id    BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    co_teacher_id BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    room          VARCHAR(30),
    CONSTRAINT chk_lessons_day CHECK (day_of_week BETWEEN 1 AND 6),
    CONSTRAINT chk_lessons_pair CHECK (pair_no BETWEEN 1 AND 6),
    CONSTRAINT chk_lessons_week CHECK (week_type IN ('EVERY', 'NUMERATOR', 'DENOMINATOR')),
    CONSTRAINT chk_lessons_name CHECK (subject_id IS NOT NULL OR title IS NOT NULL)
);

-- Экзамен / зачёт привязан к строке учебного плана: группа, дисциплина, преподаватель и форма контроля берутся оттуда
CREATE TABLE exams (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id BIGINT NOT NULL REFERENCES curriculum (id) ON DELETE CASCADE,
    exam_date     DATE   NOT NULL,
    start_time    TIME,
    room          VARCHAR(30),
    CONSTRAINT uq_exams_curriculum UNIQUE (curriculum_id)
);

CREATE INDEX idx_lessons_group ON lessons (group_id);
CREATE INDEX idx_lessons_teacher ON lessons (teacher_id);
CREATE INDEX idx_lessons_co_teacher ON lessons (co_teacher_id);
CREATE INDEX idx_exams_date ON exams (exam_date);
