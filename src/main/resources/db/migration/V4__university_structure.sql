-- Структура вуза: факультеты, кафедры, учебные группы и учебный план
-- (какая дисциплина у какой группы, кто её ведёт, семестр и форма контроля)

CREATE TABLE faculties (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE departments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(200) NOT NULL UNIQUE,
    faculty_id BIGINT       NOT NULL REFERENCES faculties (id)
);

CREATE TABLE study_groups (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(30)  NOT NULL UNIQUE,
    course     INTEGER,
    specialty  VARCHAR(150),
    faculty_id BIGINT REFERENCES faculties (id),
    CONSTRAINT chk_groups_course CHECK (course IS NULL OR course BETWEEN 1 AND 6)
);

-- Группа студента: из текстового поля в ссылку на учебную группу
ALTER TABLE users ADD COLUMN group_id BIGINT;
ALTER TABLE users ADD CONSTRAINT fk_users_group FOREIGN KEY (group_id) REFERENCES study_groups (id);
INSERT INTO study_groups (name) SELECT DISTINCT group_name FROM users WHERE group_name IS NOT NULL;
UPDATE users SET group_id = (SELECT g.id FROM study_groups g WHERE g.name = users.group_name);
DROP INDEX idx_users_group;
ALTER TABLE users DROP COLUMN group_name;

-- Кафедра преподавателя и кафедра, за которой закреплена дисциплина
ALTER TABLE users ADD COLUMN department_id BIGINT;
ALTER TABLE users ADD CONSTRAINT fk_users_department FOREIGN KEY (department_id) REFERENCES departments (id);
ALTER TABLE subjects ADD COLUMN department_id BIGINT;
ALTER TABLE subjects ADD CONSTRAINT fk_subjects_department FOREIGN KEY (department_id) REFERENCES departments (id);

-- Учебный план: дисциплина группы, преподаватель, семестр и форма контроля
CREATE TABLE curriculum (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id     BIGINT      NOT NULL REFERENCES study_groups (id) ON DELETE CASCADE,
    subject_id   BIGINT      NOT NULL REFERENCES subjects (id) ON DELETE CASCADE,
    teacher_id   BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    semester     INTEGER,
    control_form VARCHAR(20) DEFAULT 'EXAM' NOT NULL,
    CONSTRAINT uq_curriculum_group_subject UNIQUE (group_id, subject_id),
    CONSTRAINT chk_curriculum_semester CHECK (semester IS NULL OR semester BETWEEN 1 AND 12),
    CONSTRAINT chk_curriculum_control_form CHECK (control_form IN ('EXAM', 'CREDIT', 'GRADED_CREDIT'))
);

-- Форма контроля теперь задаётся в учебном плане для пары «группа + дисциплина»
ALTER TABLE subjects DROP CONSTRAINT chk_subjects_control_form;
ALTER TABLE subjects DROP COLUMN control_form;

CREATE INDEX idx_users_group ON users (group_id);
CREATE INDEX idx_users_department ON users (department_id);
CREATE INDEX idx_subjects_department ON subjects (department_id);
CREATE INDEX idx_curriculum_teacher ON curriculum (teacher_id);
CREATE INDEX idx_curriculum_subject ON curriculum (subject_id);
